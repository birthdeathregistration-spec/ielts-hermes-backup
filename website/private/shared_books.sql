CREATE TABLE IF NOT EXISTS hermes_books (
 sha CHAR(64) PRIMARY KEY, title VARCHAR(240) NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS hermes_passages (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, book_sha CHAR(64) NOT NULL,
 page_no INT UNSIGNED NOT NULL, passage TEXT NOT NULL,
 FULLTEXT KEY passage_lookup (passage),
 FOREIGN KEY (book_sha) REFERENCES hermes_books(sha) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
