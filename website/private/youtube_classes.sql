CREATE TABLE IF NOT EXISTS hermes_teacher_classes (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 teacher_id BIGINT UNSIGNED NOT NULL, video_id CHAR(11) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 title VARCHAR(180) NOT NULL, draft MEDIUMTEXT NOT NULL, approved MEDIUMTEXT NULL,
 revision INT UNSIGNED NOT NULL DEFAULT 1,
 UNIQUE KEY class_owner (teacher_id,video_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
